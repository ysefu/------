#ifndef __PROTOCOL_H
#define __PROTOCOL_H

#include "stm32f10x.h"

/*----------------------------------------------------------------------------
 * 文件：Protocol.c / Protocol.h
 * 用处：全局后台串口命令解析（HELP / TIME / ALARM / IMU / SERVO）
 *       —— 不设独立页面、不依赖当前界面，任何界面下都能收命令并立即应答
 * 对应外设：USART1（接收走中断 + 环形缓冲，见 Serial.c）
 * 对应器件：USB-TTL + 电脑串口助手
 * 备注：1) 本模块只在主循环里被调用，【不在中断里做任何解析】，所以不会阻塞
 *       2) 每次调用最多处理有限个字节和一条命令就返回，绝不长时间占着主循环
 *       3) 命令大小写不敏感（题目里 HELP 或 help 都要能识别）
 *----------------------------------------------------------------------------*/

/* 初始化命令解析器 */
void Protocol_Init(void);

/* 命令任务：主循环每 10ms 调用一次，把收到的字节拼成命令行并解析应答 */
void Protocol_Task(void);

/* 周期任务：主循环每 50ms 调用一次，负责 SERVO TRACE ON 时的 20Hz 调试数据输出 */
void Protocol_Update(void);

#endif

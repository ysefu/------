#ifndef __SERVO_H
#define __SERVO_H

#include "stm32f10x.h"

/*----------------------------------------------------------------------------
 * 文件：Servo.c / Servo.h
 * 用处：用 PWM 控制 SG90 舵机转到 0°~180° 的指定角度（舵机角度控制页 + SERVO 命令）
 * 对应外设：TIM1_CH1 → PA8 输出 50Hz PWM（0.5ms~2.5ms 脉宽对应 0°~180°）
 * 对应器件：SG90 舵机（信号线接 PA8；电源必须独立供电并与开发板共地）
 * 备注：1) 【供电警告】舵机转动电流 200~300mA、堵转可超 1A。
 *          绝不能从 ST-Link 的 5V 引脚或开发板 5V 取电：
 *          轻则电压跌落导致 MCU 复位 / 串口掉线，重则烧毁 ST-Link。
 *          请用独立 5V 电源（电池盒或 5V/2A 适配器），并与开发板共地
 *       2) 角度变化不是"一步跳过去"，而是内部按每 20ms 最多 2° 平滑逼近，
 *          避免舵机瞬间大角度跳动导致电流冲击
 *       3) 上电默认角度 90°（题目要求），离开页面后保持最后一次有效角度
 *----------------------------------------------------------------------------*/

/* 初始化：PA8 输出 50Hz PWM，并转到默认角度 90° */
void Servo_Init(void);

/* 设置目标角度（自动限制在 0~180），返回实际生效的角度 */
uint8_t Servo_SetAngle(uint8_t Angle);

/* 读取当前目标角度 0~180 */
uint8_t Servo_GetAngle(void);

/* 读取当前实际输出角度（平滑过程中的中间值），单位 0.1° */
uint16_t Servo_GetOutputAngle10(void);

/* 平滑逼近任务：主循环里每 20ms 调用一次 */
void Servo_Update(void);

/*============================================================================
 * 以下为"发挥要求（3）基于 IMU 的舵机姿态定角"用到的接口
 * 闭环原理：IMU 装在舵机驱动的被控机构上，把 IMU 的 Pitch 角当作被控姿态角（本机实测反向）
 *============================================================================*/

/* 启动定角：捕获当前 IMU 姿态角作为目标姿态（上电默认关闭，开启时捕获当前姿态） */
void Servo_HoldStart(void);

/* 现场调试用：立刻把当前姿态重新记为目标姿态（"记录当前位置"） */
void Servo_HoldCal(void);

/* 开启 / 关闭闭环定角：1=开（并以当前姿态为目标），0=关（清除定角故障） */
void Servo_SetHold(uint8_t Enable);

/* 定角是否开启：1=开启 */
uint8_t Servo_GetHold(void);

/* 定角故障标志：1=有锁存故障，停止PWM调节；关闭定角后清除 */
uint8_t Servo_GetHoldFault(void);

/* 设置目标姿态角，单位 0.1°（如 150 = 15.0°，允许 -30.0°~+30.0°） */
void Servo_SetHoldAngle10(int16_t Angle10);

/* 读取目标姿态角，单位 0.1° */
int16_t Servo_GetHoldAngle10(void);

/* 读取当前姿态角（取闭环实际使用的那一个轴），单位 0.1° */
int16_t Servo_GetHoldCurAngle10(void);

/* 读取定角偏差（目标 − 当前），单位 0.1° */
int16_t Servo_GetHoldErr10(void);

/* 定角闭环任务：主循环里每 20ms 调用一次（内部自己判断是否开启） */
void Servo_HoldTask(void);

/* 功能：读取锁存故障原因码；无参数，0正常，1数据无效，2启用条件，3时序，4偏差，5反馈，6行程。 */
uint8_t Servo_GetHoldFaultCode(void);
#endif
